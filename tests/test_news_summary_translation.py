def test_the_local_model_result_keeps_the_title_sections_and_is_tried_first(monkeypatch):
    from app.services import news_summary_service as s

    seen = []

    def fake_translate(texts, target="ms"):
        seen.append((texts, target))
        return ["ms:" + x for x in texts]

    monkeypatch.setattr(s.local_translate_service, "translate_texts", fake_translate)
    out = s._translate_local(EN)
    assert out == ("TITLE: ms:Stablecoin Shutdown\nms:Kyrgyzstan has shut down USDKG.\n\nTITLE: ms:Wider Rules\nms:South Korea tightens cross-border rules.", s.LOCAL_MODEL_NAME)
    assert seen == [(["Stablecoin Shutdown", "Kyrgyzstan has shut down USDKG.", "Wider Rules", "South Korea tightens cross-border rules."], "ms")]  # one call, in order
    assert s.translation_has_same_sections(EN, out[0])
    assert s._translate(EN) == out  # _translate takes the local answer without touching the AI models (no key / network needed)


def test_without_the_model_the_local_path_returns_nothing_and_the_ai_is_the_fallback(monkeypatch):
    from app.services import news_summary_service as s

    monkeypatch.setattr(s.local_translate_service, "translate_texts", lambda texts, target="ms": None)
    assert s._translate_local(EN) is None
    asked = []
    monkeypatch.setattr(s, "_call_model", lambda prompt, model, system=None, max_tokens=600: (asked.append(model), (MS_OK, "m"))[1])
    assert s._translate(EN) == (MS_OK, "m") and asked  # the AI models were asked


def test_the_note_says_why_the_translation_is_missing(monkeypatch):
    from app.services import ai_budget
    from app.services import news_summary_service as s

    monkeypatch.setattr(s.local_translate_service, "is_available", lambda: False)
    monkeypatch.setattr(ai_budget, "blocked", lambda: True)
    assert "not installed" in s.unavailable_reason() and "daily limit" in s.unavailable_reason() and "08:00" in s.unavailable_reason()
    monkeypatch.setattr(ai_budget, "blocked", lambda: False)
    assert s.unavailable_reason() == "The local translation model is not installed on this server."
    monkeypatch.setattr(s.local_translate_service, "is_available", lambda: True)
    assert "not available right now" in s.unavailable_reason()


