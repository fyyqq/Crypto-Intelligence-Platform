def test_google_translate_keeps_the_title_sections_and_is_tried_first(monkeypatch):
    from app.services import news_summary_service as s

    calls = []

    class Reply:
        status_code = 200

        def raise_for_status(self):
            pass

        def json(self):
            return {"data": {"translations": [{"translatedText": t} for t in calls[-1]["q"]]}}  # echoes: only the structure is under test

    def fake_post(url, params=None, json=None, timeout=None):
        calls.append(json)
        assert url == s.GOOGLE_ENDPOINT and params == {"key": "k"}  # the official endpoint, the key only in the query
        return Reply()

    monkeypatch.setattr(s.requests, "post", fake_post)
    monkeypatch.setattr(s.settings, "google_translate_api_key", "k")
    out = s._translate_google(EN)
    assert out == (EN, s.GOOGLE_MODEL_NAME)  # same TITLE: format back, headings and paragraphs in order
    assert calls[0]["q"] == ["Stablecoin Shutdown", "Kyrgyzstan has shut down USDKG.", "Wider Rules", "South Korea tightens cross-border rules."]
    assert calls[0]["source"] == "en" and calls[0]["target"] == "ms" and calls[0]["format"] == "text"
    assert s._translate(EN) == (EN, s.GOOGLE_MODEL_NAME)  # _translate takes Google's answer without touching the AI models


def test_google_translate_without_a_key_or_on_an_error_falls_back(monkeypatch):
    from app.services import news_summary_service as s

    monkeypatch.setattr(s.settings, "google_translate_api_key", "")
    assert s._translate_google(EN) is None  # no key: nothing is sent anywhere
    monkeypatch.setattr(s.settings, "google_translate_api_key", "k")

    def boom(*a, **k):
        raise s.requests.ConnectionError("down")

    monkeypatch.setattr(s.requests, "post", boom)
    assert s._translate_google(EN) is None


def test_the_note_says_why_the_translation_is_missing(monkeypatch):
    from app.services import ai_budget
    from app.services import news_summary_service as s

    monkeypatch.setattr(ai_budget, "blocked", lambda: True)
    assert "daily limit" in s.unavailable_reason() and "08:00" in s.unavailable_reason()
    monkeypatch.setattr(ai_budget, "blocked", lambda: False)
    monkeypatch.setattr(s.settings, "openrouter_api_key", "")
    monkeypatch.setattr(s.settings, "google_translate_api_key", "")
    assert "No translation service" in s.unavailable_reason()
